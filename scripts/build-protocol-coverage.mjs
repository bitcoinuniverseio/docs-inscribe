#!/usr/bin/env node
// Regenerates src/data/protocol-coverage.json from the platform ecosystem
// registry snapshot, which is generated in turn from the Core protocol
// contracts module. The coverage matrix on this site is therefore derived,
// never typed: a protocol cannot be claimed here unless the registry records
// an `inscribe` surface for it, and the operations listed are exactly the
// ones the registry records.
//
// The snapshot is not a dependency of this repository. Run this from a
// checkout that has the docs-platform repository beside it and pass the path:
//
//   node scripts/build-protocol-coverage.mjs \
//     ../docs-platform/packages/ecosystem-registry/data/capability-snapshot.json
//
// then review and commit the changed JSON. `npm run check:capabilities`
// verifies the committed file against itself on every build, and fails if a
// page claims an operation the file does not carry.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');

const snapshotPath = process.argv[2];
if (snapshotPath === undefined) {
  console.error('usage: build-protocol-coverage.mjs <path to capability-snapshot.json>');
  process.exit(2);
}

const snapshot = JSON.parse(readFileSync(resolve(snapshotPath), 'utf8'));
const protocols = Object.values(snapshot.protocols);

// Families group the matrix for reading. Membership is editorial; the
// operations, chain, ownership model and address roles are not.
const FAMILY = {
  ordinals: 'ordinals',
  brc20: 'ordinals',
  tap: 'ordinals',
  block20: 'ordinals',
  bitmap: 'ordinals',
  unat: 'ordinals',
  runes: 'runes',
  mezcal: 'runes',
  alkanes: 'runes',
  stamps: 'stamps',
  src20: 'stamps',
  src101: 'stamps',
  atomicals: 'atomicals',
  arc20: 'atomicals',
  atomicals_nft: 'atomicals',
  realms: 'atomicals',
  subrealms: 'atomicals',
  avm: 'atomicals',
  op_return: 'op-return',
  op_drop: 'op-return',
  drops: 'op-return',
  cat20: 'other',
  dust20: 'other',
  chainbloom: 'other',
  doginals: 'dogecoin',
  drc20: 'dogecoin',
  tap_doge: 'dogecoin',
};

const inscribable = protocols
  .filter((p) => p.surfaces?.inscribe)
  .map((p) => ({
    id: p.id,
    name: p.displayName,
    aliases: p.aliases ?? [],
    family: FAMILY[p.id] ?? 'other',
    chain: p.chain,
    ownershipModel: p.ownershipModel,
    decimals: p.decimals,
    addressRoles: p.addressRoles ?? [],
    // The operations Inscribe implements for this protocol, verbatim.
    creation: p.surfaces.inscribe.actions ?? [],
    // Other surfaces the same protocol appears on, so a reader can see that
    // being creatable here says nothing about being tradeable elsewhere.
    otherSurfaces: Object.keys(p.surfaces).filter((s) => s !== 'inscribe'),
    // Marketplace availability is recorded so the site can state plainly that
    // creation and trading are independent. Null means the registry records
    // no marketplace entry at all.
    marketplaceAvailability: p.marketplace?.availability ?? null,
  }))
  .sort((a, b) => a.name.localeCompare(b.name));

const notInscribable = protocols
  .filter((p) => !p.surfaces?.inscribe)
  .map((p) => ({
    id: p.id,
    name: p.displayName,
    chain: p.chain,
    surfaces: Object.keys(p.surfaces ?? {}),
  }))
  .sort((a, b) => a.name.localeCompare(b.name));

const operations = [...new Set(inscribable.flatMap((p) => p.creation))].sort();

const output = {
  $comment:
    'Generated by scripts/build-protocol-coverage.mjs. Do not edit by hand. Every operation here is recorded in the Core protocol registry.',
  provenance: snapshot.provenance,
  counts: {
    protocolsTotal: protocols.length,
    protocolsWithInscribeSurface: inscribable.length,
    protocolsWithoutInscribeSurface: notInscribable.length,
  },
  operations,
  inscribable,
  notInscribable,
};

writeFileSync(
  resolve(root, 'src/data/protocol-coverage.json'),
  JSON.stringify(output, null, 2) + '\n',
);

console.log(
  `wrote src/data/protocol-coverage.json: ${inscribable.length} protocols with an inscribe surface, ${notInscribable.length} without`,
);
